alter table anasap disable all triggers
/
update anasap
   set id                  = ANASAP_SQ.nextval,
       id_pratica          = f_ANA_get_id_pratica(anagrafe,tipo_evento,anno_pratica,pratica),
       d_data_evento       = to_date(data_evento,'j'),
       d_data_restituzione = to_date(data_restituzione,'j')
 where id is null
/
update anasap sap
   set id_anatpr           = (select id from anatpr
                               where anagrafe = sap.anagrafe
                                 and tipo_evento = sap.tipo_evento
                                 and anno_pratica = sap.anno_pratica
                                 and pratica      = sap.pratica
                                 and rownum = 1)
 where id_anatpr is null
/
alter table anasap enable all triggers
