alter table anacrm disable all triggers
/
update anacrm
   set id                    = ANACRM_SQ.nextval,
       id_pratica            = f_ANA_get_id_pratica('RES','E',anno_pratica,pratica)
 where id is null
/
update anacrm crm
   set id_anacre = (select cre.id from anacre cre
                     where cre.anno_pratica = crm.anno_pratica
                       and cre.pratica      = crm.pratica
                       and rownum = 1)
 where id_anacre is null
/
update anacrm crm
   set id_anatpr = (select cre.id_anatpr from anacre cre
                     where cre.anno_pratica = crm.anno_pratica
                       and cre.pratica      = crm.pratica
                       and rownum = 1)
 where id_anatpr is null
/
alter table anacrm enable all triggers	
