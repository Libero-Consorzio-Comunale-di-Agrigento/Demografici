alter table anadoi disable all triggers
/
update anadoi
   set id             		  = ANADOI_SQ.nextval,
       id_pratica     		  = f_ANA_get_id_pratica(anagrafe,tipo_evento,anno_pratica,pratica),
       d_data_contratto_locazione = to_date(data_contratto_locazione,'j'),
       d_data_contratto_comodato  = to_date(data_contratto_comodato,'j')
 where id is null
/
update anadoi doi
   set id_anatpr = (select tpr.id from anatpr tpr
                     where tpr.anagrafe     = doi.anagrafe
                       and tpr.tipo_evento  = doi.tipo_evento
                       and tpr.anno_pratica = doi.anno_pratica
                       and tpr.pratica      = doi.pratica
                       and rownum = 1)
 where id_anatpr is null
/
alter table anadoi enable all triggers
/
