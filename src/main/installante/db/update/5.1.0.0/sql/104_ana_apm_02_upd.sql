alter table anaapm disable all triggers
/
update anaapm
   set id                    = ANAAPM_SQ.nextval,
       id_dichiarazione      = f_ANA_get_id_pratica('RES','I',anno_dic,numero_dic)
 where id is null
/
update anaapm apm
   set id_anaap4 = (select ap4.id from anaap4 ap4
                     where ap4.anno_dic   = apm.anno_dic
                       and ap4.numero_dic = apm.numero_dic
                       and rownum = 1)
 where id_anaap4 is null
/
update anaapm apm
   set id_anatpr = (select ap4.id_anatpr from anaap4 ap4
                     where ap4.anno_dic   = apm.anno_dic
                       and ap4.numero_dic = apm.numero_dic
                       and rownum = 1)
 where id_anatpr is null
/
alter table anaapm enable all triggers
/
